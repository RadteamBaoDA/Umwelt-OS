def _w2_count(sql: str, parameters: dict[str, object] | None = None) -> int:
    """Return an explicit audit count on the Alembic transaction, without importing ORM."""
    return int(op.get_bind().execute(sa.text(sql), parameters or {}).scalar_one())


def _w2_fail_rows(
    table: str, reason: str, predicate: str, parameters: dict[str, object] | None = None,
) -> None:
    """Abort with table and offending row count; identifiers come only from finite manifests."""
    count = _w2_count(f'SELECT count(*) FROM "{table}" t WHERE {predicate}', parameters)
    if count:
        raise RuntimeError(f"W2 workspace cutover: table={table} count={count}: {reason}")


def _w2_singleton_scope() -> UUID | None:
    """Prove the documented legacy singleton manifest; never fabricate or choose an account.

    Exactly one bootstrap account and one owned default workspace are required. A missing,
    foreign or incomplete identity is not a fallback lineage source. Disabled account state
    does not erase historical ownership; this proof never authorizes runtime access.
    """
    if _w2_count('SELECT count(*) FROM owner') != 1 or _w2_count('SELECT count(*) FROM workspaces') != 1:
        return None
    value = op.get_bind().execute(sa.text(
        "SELECT w.id FROM workspaces w JOIN owner o ON o.default_workspace_id = w.id "
        "AND w.owner_user_id = o.id WHERE o.id = 1 AND w.is_default"
    )).scalar_one_or_none()
    return value


def _w2_empty_replay() -> None:
    """Remove only the historical idle replay metadata sentinel before empty setup migration.

    r06 used uuid4 and seeded id1 before any owner existed. Any event, extra head, unexpected
    sequence/floor or non-v4 epoch fails. A later gate failure rolls this removal back with
    the migration transaction; no history is discarded to make an invalid database pass.
    """
    if _w2_count('SELECT count(*) FROM owner') or _w2_count('SELECT count(*) FROM workspaces'):
        return
    _w2_fail_rows('realtime_replay_events', 'replay history exists without an account/default workspace', 'TRUE')
    _w2_fail_rows(
        'realtime_replay_head', 'unexpected ownerless replay metadata',
        "t.id <> 1 OR t.sequence <> 0 OR t.floor_sequence <> 1 OR t.epoch IS NULL "
        "OR t.epoch::text !~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' "
        "OR t.updated_at IS NULL",
    )
    op.execute(sa.text('DELETE FROM realtime_replay_head WHERE id = 1 AND sequence = 0 AND floor_sequence = 1'))


def _w2_scope_sql(table: str, alias: str, depth: int = 0) -> str:
    """Resolve one row's scope through a finite inherited path; child columns stay unchanged."""
    if table in SCOPED_TABLES:
        return f'{alias}.workspace_id'
    column, parent, key = INHERITED_PATHS[table]
    parent_alias = f'p{depth}'
    parent_scope = _w2_scope_sql(parent, parent_alias, depth + 1)
    return f'(SELECT {parent_scope} FROM "{parent}" {parent_alias} WHERE {parent_alias}."{key}" = {alias}."{column}")'


def _w2_candidates(table: str) -> str:
    """Build source/parent/account proof candidates; detached missing IDs supply no authority."""
    selects = []
    for child, column, parent, key in LINEAGE_REFERENCES:
        if child == table:
            selects.append(
                f'SELECT {_w2_scope_sql(parent, "p")} AS workspace_id FROM "{parent}" p '
                f'WHERE p."{key}" = t."{column}"'
            )
    for child, actor in EXISTING_ACTORS:
        if child == table:
            selects.append(f'SELECT o.default_workspace_id AS workspace_id FROM owner o WHERE o.id = t."{actor}"')
    return ' UNION ALL '.join(selects) or 'SELECT NULL::uuid AS workspace_id'


def _w2_validate_live() -> None:
    """Refuse orphan live FKs and incomplete account/default lineage before assigning any scope."""
    for table, column, parent, key in LIVE_REFERENCES:
        _w2_fail_rows(
            table, f'orphan live parent {column}->{parent}.{key}',
            f't."{column}" IS NOT NULL AND NOT EXISTS (SELECT 1 FROM "{parent}" p WHERE p."{key}" = t."{column}")',
        )
    for table, actor in EXISTING_ACTORS:
        _w2_fail_rows(
            table, f'missing actor/default ownership for {actor}',
            f'NOT EXISTS (SELECT 1 FROM owner o JOIN workspaces w ON w.id = o.default_workspace_id '
            f'AND w.owner_user_id = o.id AND w.is_default WHERE o.id = t."{actor}")',
        )


def _w2_backfill() -> None:
    """Backfill proven lineage first, then guarded singleton roots/retained historical receipts.

    A finite number of passes resolves parent-first dependencies without metadata traversal.
    Every available live proof must agree. A singleton fallback is allowed only after exact
    live/account orphan gates; it cannot rescue a missing owner or missing required parent.
    Durable job/delivery epochs come from the matching current owner membership under
    cutover locks; missing or mismatched authority aborts with table/count, never epoch1.
    """
    bind = op.get_bind()
    singleton = _w2_singleton_scope()
    # Legacy Source has no actor/owner column. Prove this root first so Document and
    # ingestion descendants backfill through their real Source, not a blanket fallback.
    if singleton is None:
        _w2_fail_rows('sources', 'unowned legacy Source requires the verified singleton cutover manifest', 't.workspace_id IS NULL')
    else:
        bind.execute(sa.text('UPDATE sources SET workspace_id = :workspace WHERE workspace_id IS NULL'), {'workspace': singleton})
    for _ in range(len(SCOPED_TABLES)):
        changed = 0
        for table in SCOPED_TABLES:
            candidates = _w2_candidates(table)
            _w2_fail_rows(
                table, 'ambiguous source/parent/account workspace lineage',
                f'(SELECT count(DISTINCT proof.workspace_id) FROM ({candidates}) proof) > 1',
            )
            result = bind.execute(sa.text(
                f'UPDATE "{table}" t SET workspace_id = (SELECT min(proof.workspace_id::text)::uuid '
                f'FROM ({candidates}) proof) WHERE t.workspace_id IS NULL AND EXISTS '
                f'(SELECT 1 FROM ({candidates}) proof WHERE proof.workspace_id IS NOT NULL)'
            ))
            changed += result.rowcount
        if not changed:
            break
    for table in SCOPED_TABLES:
        if singleton is None:
            _w2_fail_rows(table, 'unresolved scope; verified singleton cutover manifest unavailable', 't.workspace_id IS NULL')
        else:
            # The singleton decision above is a proof, never an unconditional owner=1 update.
            bind.execute(sa.text(f'UPDATE "{table}" SET workspace_id = :workspace WHERE workspace_id IS NULL'), {'workspace': singleton})
    for table, actor in NEW_ACTORS:
        bind.execute(sa.text(
            f'UPDATE "{table}" t SET "{actor}" = w.owner_user_id FROM workspaces w '
            f'WHERE w.id = t.workspace_id AND t."{actor}" IS NULL'
        ))
        _w2_fail_rows(table, f'unresolved actor {actor}', f't."{actor}" IS NULL')
    # A run's Source must prove its scope before capturing durable execution authority.
    _w2_fail_rows(
        'ingestion_runs', 'unproven Source workspace lineage for authorization epoch',
        'NOT EXISTS (SELECT 1 FROM sources s WHERE s.id = t.source_id '
        'AND s.workspace_id = t.workspace_id)',
    )
    for table in ('ingestion_runs', 'event_outbox'):
        _w2_fail_rows(
            table, 'actor/default workspace mismatch for authorization epoch',
            'NOT EXISTS (SELECT 1 FROM workspaces w JOIN owner o ON o.id = w.owner_user_id '
            'AND o.default_workspace_id = w.id WHERE w.id = t.workspace_id '
            'AND w.owner_user_id = t.actor_user_id AND w.is_default)',
        )
        # Capture the actual current epoch. Membership revisions remain mutable; no FK
        # to the revision or bootstrap fallback can stand in for later runtime validation.
        bind.execute(sa.text(
            f'UPDATE "{table}" t SET membership_revision = m.revision '
            'FROM workspace_memberships m WHERE m.workspace_id = t.workspace_id '
            "AND m.user_id = t.actor_user_id AND m.role = 'owner' AND m.revision > 0"
        ))
        _w2_fail_rows(
            table, 'missing or mismatched positive owner membership authorization epoch',
            't.membership_revision IS NULL OR t.membership_revision <= 0 OR NOT EXISTS '
            '(SELECT 1 FROM workspace_memberships m WHERE m.workspace_id = t.workspace_id '
            "AND m.user_id = t.actor_user_id AND m.role = 'owner' "
            'AND m.revision = t.membership_revision AND m.revision > 0)',
        )
    # The cutover captures a fresh durable authorization epoch under the same identity locks.
    # Source retirement may outlive the Source/outbox; it must not reconstruct job authority
    # later through foreign Ingestion state or an unconditional bootstrap membership.
    bind.execute(sa.text(
        'UPDATE source_purge_operations t SET membership_revision = m.revision '
        'FROM workspace_memberships m WHERE m.workspace_id = t.workspace_id '
        "AND m.user_id = t.actor_user_id AND m.role = 'owner' AND m.revision > 0"
    ))
    _w2_fail_rows('source_purge_operations', 'missing positive owner membership authorization epoch',
                  't.membership_revision IS NULL OR t.membership_revision <= 0')


def _w2_validate_lineage() -> None:
    """Reject mismatched multi-parent scope after backfill, including retained pointers that live.

    Canonical missing detached IDs are permitted; they never gain live FKs. Inherited child
    paths must agree with every other live evidence root, before NOT NULL/DDL contraction.
    """
    for table, column, parent, key in LINEAGE_REFERENCES:
        if table not in SCOPED_TABLES and table not in INHERITED_PATHS:
            continue
        row_scope = _w2_scope_sql(table, 't')
        parent_scope = _w2_scope_sql(parent, 'p')
        _w2_fail_rows(
            table, f'workspace mismatch at {column}->{parent}.{key}',
            f'EXISTS (SELECT 1 FROM "{parent}" p WHERE p."{key}" = t."{column}" '
            f'AND {parent_scope} IS DISTINCT FROM {row_scope})',
        )
    for table, actor in EXISTING_ACTORS:
        if table in SCOPED_TABLES or table in INHERITED_PATHS:
            _w2_fail_rows(
                table, f'actor/default workspace mismatch for {actor}',
                f'NOT EXISTS (SELECT 1 FROM owner o WHERE o.id = t."{actor}" '
                f'AND o.default_workspace_id = {_w2_scope_sql(table, "t")})',
            )
    for table in SCOPED_TABLES:
        _w2_fail_rows(table, 'unresolved workspace', 't.workspace_id IS NULL')
    # Legacy replay records must actually belong to the proven head epoch and sequence range.
    _w2_fail_rows(
        'realtime_replay_events', 'replay epoch/head/range mismatch',
        'NOT EXISTS (SELECT 1 FROM realtime_replay_head h WHERE h.workspace_id = t.workspace_id '
        'AND h.user_id = t.user_id AND h.epoch = t.epoch AND t.sequence <= h.sequence '
        'AND t.sequence >= h.floor_sequence)',
    )


def upgrade() -> None:
    """Expand, prove all lineage, enforce scope, then replace only finite legacy identities.

    Cutover must stop writers and drain/fence external operations before invoking Alembic.
    Database locks prevent concurrent identity/lineage mutation during these proofs. They
    are migration-only locks, not a new runtime authorization/publication mechanism.
    Agent/browser original epochs remain nullable and unfilled: current membership or
    configuration is no historical receipt, and consumers must quarantine missing pairs.
    """
    tables = sorted(set(SCOPED_TABLES) | set(INHERITED_PATHS) | {'owner', 'workspaces', 'workspace_memberships'})
    op.execute(sa.text('LOCK TABLE ' + ', '.join(f'"{table}"' for table in tables) + ' IN ACCESS EXCLUSIVE MODE'))
    offline = context.is_offline_mode()  # --sql has no bind; data proofs run online only
    if not offline:
        _w2_empty_replay()
        _w2_validate_live()
    for table, columns in SCOPED_COLUMNS:
        for column in columns:
            column_type = (postgresql.UUID(as_uuid=True) if column == 'workspace_id'
                           else sa.BigInteger() if column == 'membership_revision' else sa.Integer())
            op.add_column(table, sa.Column(column, column_type, nullable=True))
    # Keep original admission epochs outside SCOPED_COLUMNS' NOT NULL contraction.
    # No proven historical receipt exists; every legacy pair stays NULL, without defaults.
    for table in ('agent_runs', 'browser_read_jobs'):
        op.add_column(table, sa.Column('membership_revision', sa.BigInteger(), nullable=True))
        op.add_column(table, sa.Column('configuration_revision', sa.Integer(), nullable=True))
        op.create_check_constraint(
            f'ck_w2_{table}_original_epoch', table,
            '(membership_revision IS NULL AND configuration_revision IS NULL) OR '
            '(membership_revision IS NOT NULL AND configuration_revision IS NOT NULL '
            'AND membership_revision > 0 AND configuration_revision > 0)',
        )
    if not offline:
        _w2_backfill()
        _w2_validate_lineage()
    for table, columns in SCOPED_COLUMNS:
        for column in columns:
            op.alter_column(table, column, nullable=False)
    for table, actor in ACTOR_DEFAULT_DROPS:
        op.alter_column(table, actor, server_default=None)
    op.create_check_constraint('ck_w2_source_purge_membership_revision_positive',
                               'source_purge_operations', 'membership_revision > 0')
    op.create_check_constraint('ck_w2_ingestion_runs_membership_revision_positive',
                               'ingestion_runs', 'membership_revision > 0')
    op.create_check_constraint('ck_w2_event_outbox_membership_revision_positive',
                               'event_outbox', 'membership_revision > 0')
    for table, constraint, _ in CHECK_REPLACEMENTS:
        op.drop_constraint(constraint, table, type_='check')
        if constraint == 'ck_chat_agent_activity_owner_auth':
            op.create_check_constraint(constraint, table, 'length(auth_session_hash) = 64')
    op.drop_constraint('ck_realtime_replay_event_type', 'realtime_replay_events', type_='check')
    op.create_check_constraint(
        'ck_realtime_replay_event_type', 'realtime_replay_events',
        "event_type IN ('source.changed', 'ingestion.changed', 'knowledge.changed', 'dashboard.changed')",
    )
    op.drop_constraint('ck_realtime_replay_head_singleton', 'realtime_replay_head', type_='check')
    for table, old_columns, columns in PRIMARY_KEYS:
        op.drop_constraint(f'{table}_pkey', table, type_='primary')
        op.create_primary_key(f'{table}_pkey', table, list(columns))
        if old_columns == ['id'] and table in ('realtime_replay_head', 'news_recovery_checkpoints'):
            op.drop_column(table, 'id')
    for table, constraint, old_columns, columns in UNIQUE_REPLACEMENTS:
        if old_columns is not None:
            op.drop_constraint(constraint, table, type_='unique')
        op.create_unique_constraint(constraint, table, list(columns))
    for table, index, old_columns, columns, predicate in INDEX_REPLACEMENTS:
        if old_columns is not None:
            op.drop_index(index, table_name=table)
        op.create_index(index, table, list(columns), unique=predicate is not None,
                        **({'postgresql_where': sa.text(predicate)} if predicate is not None else {}))
    for table, constraint, _, _, _, _ in OLD_FOREIGN_KEYS:
        op.drop_constraint(constraint, table, type_='foreignkey')
    for table, constraint, parent, columns, keys, delete, deferred in NEW_FOREIGN_KEYS:
        # Existing scalar SET NULL performs the nullable-ID update. The matching deferred
        # NO ACTION composite never sets retained workspace_id to NULL on parent deletion.
        op.create_foreign_key(constraint, table, parent, list(columns), list(keys),
                              ondelete=delete, **({'deferrable': True, 'initially': 'DEFERRED'} if deferred else {}))


def _w2_downgrade_guard() -> None:
    """Prove singleton representation without deleting accounts, scopes, recipients or data.

    Captured job/delivery epochs other than bootstrap revision1 cannot survive legacy
    representation; reject them with table/count before any destructive downgrade DDL.
    Dashboard replay history is also unrepresentable by the historical three-kind CHECK;
    refuse its retained rows rather than delete them to force a downgrade.
    """
    _w2_fail_rows('owner', 'downgrade cannot represent nonbootstrap accounts', 't.id <> 1')
    _w2_fail_rows('workspaces', 'downgrade cannot represent foreign/nondefault workspaces', 't.owner_user_id <> 1 OR NOT t.is_default')
    _w2_fail_rows('workspace_memberships', 'downgrade cannot represent nonbootstrap recipients', "t.user_id <> 1 OR t.role <> 'owner'")
    singleton = _w2_singleton_scope()
    for table in SCOPED_TABLES:
        if singleton is None:
            _w2_fail_rows(table, 'scoped data has no verified bootstrap singleton', 'TRUE')
        else:
            _w2_fail_rows(table, 'foreign workspace data cannot be downgraded', 't.workspace_id IS DISTINCT FROM :workspace', {'workspace': singleton})
    for table, actor in EXISTING_ACTORS + NEW_ACTORS:
        _w2_fail_rows(table, f'nonbootstrap actor {actor} cannot be downgraded', f't."{actor}" <> 1')
    _w2_fail_rows('source_purge_operations', 'legacy jobs cannot represent a later membership authorization epoch',
                  't.membership_revision <> 1')
    for table in ('ingestion_runs', 'event_outbox'):
        _w2_fail_rows(table, 'legacy jobs/delivery cannot represent a later membership authorization epoch',
                      't.membership_revision <> 1')
    _w2_fail_rows('realtime_replay_events', 'legacy replay cannot represent dashboard.changed history',
                  "t.event_type = 'dashboard.changed'")
    for table, constraint, columns, _ in UNIQUE_REPLACEMENTS:
        if columns is not None:
            # Old SQL uniqueness permits any tuple containing NULL; guard only real collisions.
            nonnull = ' AND '.join(f'"{column}" IS NOT NULL' for column in columns)
            grouped = ', '.join(f'"{column}"' for column in columns)
            count = _w2_count(f'SELECT coalesce(sum(n), 0) FROM (SELECT count(*) n FROM "{table}" '
                              f'WHERE {nonnull} GROUP BY {grouped} HAVING count(*) > 1) conflicts')
            if count:
                raise RuntimeError(f'W2 downgrade: table={table} count={count}: legacy unique collision {constraint}')
    for table, old_columns, _ in PRIMARY_KEYS:
        singleton_key = old_columns == ['id'] and table in ('realtime_replay_head', 'news_recovery_checkpoints')
        grouping = '' if singleton_key else ' GROUP BY ' + ', '.join(f'"{column}"' for column in old_columns)
        count = _w2_count(f'SELECT coalesce(sum(n), 0) FROM (SELECT count(*) n FROM "{table}"'
                          + grouping + ' HAVING count(*) > 1) conflicts')
        if count:
            raise RuntimeError(f'W2 downgrade: table={table} count={count}: legacy primary-key collision')
    _w2_fail_rows('search_index_generations', 'multiple active generations cannot be downgraded',
                  "t.status = 'active' AND (SELECT count(*) FROM search_index_generations WHERE status = 'active') > 1")


def downgrade() -> None:
    """Refuse unrepresentable state first, then restore singleton identities without content loss.

    Identity downgrade is a later operation in this chain. The only inserted row is the
    historical empty replay metadata head, required by the earlier unpublished schema.
    Restore the old replay kinds only after refusing dashboard history. Remove original
    Agent/browser epoch checks before their nullable columns; never synthesize authority.
    """
    tables = sorted(set(SCOPED_TABLES) | set(INHERITED_PATHS) | {'owner', 'workspaces', 'workspace_memberships'})
    op.execute(sa.text('LOCK TABLE ' + ', '.join(f'"{table}"' for table in tables) + ' IN ACCESS EXCLUSIVE MODE'))
    _w2_downgrade_guard()
    for table, constraint, _, _, _, _, _ in reversed(NEW_FOREIGN_KEYS):
        op.drop_constraint(constraint, table, type_='foreignkey')
    for table, constraint, parent, columns, keys, delete in OLD_FOREIGN_KEYS:
        op.create_foreign_key(constraint, table, parent, list(columns), list(keys), ondelete=delete)
    for table, index, old_columns, _, predicate in reversed(INDEX_REPLACEMENTS):
        op.drop_index(index, table_name=table)
        if old_columns is not None:
            op.create_index(index, table, list(old_columns), unique=True, postgresql_where=sa.text(predicate))
    for table, constraint, old_columns, _ in reversed(UNIQUE_REPLACEMENTS):
        op.drop_constraint(constraint, table, type_='unique')
        if old_columns is not None:
            op.create_unique_constraint(constraint, table, list(old_columns))
    for table, old_columns, _ in reversed(PRIMARY_KEYS):
        op.drop_constraint(f'{table}_pkey', table, type_='primary')
        if old_columns == ['id'] and table in ('realtime_replay_head', 'news_recovery_checkpoints'):
            column_type = sa.SmallInteger() if table == 'realtime_replay_head' else sa.Integer()
            op.add_column(table, sa.Column('id', column_type, nullable=False, server_default='1'))
            op.alter_column(table, 'id', server_default=None)
        op.create_primary_key(f'{table}_pkey', table, list(old_columns))
    for table, constraint, predicate in CHECK_REPLACEMENTS:
        if constraint == 'ck_chat_agent_activity_owner_auth':
            op.drop_constraint(constraint, table, type_='check')
        op.create_check_constraint(constraint, table, predicate)
    op.drop_constraint('ck_realtime_replay_event_type', 'realtime_replay_events', type_='check')
    op.create_check_constraint(
        'ck_realtime_replay_event_type', 'realtime_replay_events',
        "event_type IN ('source.changed', 'ingestion.changed', 'knowledge.changed')",
    )
    for table in ('agent_runs', 'browser_read_jobs'):
        op.drop_constraint(f'ck_w2_{table}_original_epoch', table, type_='check')
        op.drop_column(table, 'configuration_revision')
        op.drop_column(table, 'membership_revision')
    op.create_check_constraint('ck_realtime_replay_head_singleton', 'realtime_replay_head', 'id = 1')
    op.drop_constraint('ck_w2_source_purge_membership_revision_positive', 'source_purge_operations', type_='check')
    op.drop_constraint('ck_w2_ingestion_runs_membership_revision_positive', 'ingestion_runs', type_='check')
    op.drop_constraint('ck_w2_event_outbox_membership_revision_positive', 'event_outbox', type_='check')
    for table, columns in reversed(SCOPED_COLUMNS):
        for column in reversed(columns):
            op.drop_column(table, column)
    for table, actor, default in LEGACY_ACTOR_DEFAULTS:
        op.alter_column(table, actor, server_default=default)
    if not _w2_count('SELECT count(*) FROM realtime_replay_head'):
        op.get_bind().execute(sa.text(
            'INSERT INTO realtime_replay_head(id, epoch, sequence, floor_sequence) VALUES (1, :epoch, 0, 1)'
        ), {'epoch': uuid4()})

