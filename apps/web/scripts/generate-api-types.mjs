#!/usr/bin/env node
/**
 * Generates `src/core/api-types.gen.ts` from the FastAPI OpenAPI schema using openapi-typescript.
 *
 * The schema is produced offline by importing `apps.api.main:create_app` (no server, database or network) with
 * placeholder non-production settings. Usage:
 *   npm run gen:api --workspace apps/web          # regenerate the committed file
 *   npm run gen:api:check --workspace apps/web    # CI: exit 1 when the committed file is stale
 *
 * The Python interpreter is taken from $UMWELT_PYTHON, else the repo `.venv`, else `python3`.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../../..');
const outFile = resolve(here, '../src/core/api-types.gen.ts');
const check = process.argv.includes('--check');

/** Picks the Python interpreter that can import the backend (env override, repo venv, then PATH). */
function pythonBinary() {
  if (process.env.UMWELT_PYTHON) return process.env.UMWELT_PYTHON;
  for (const candidate of ['.venv/bin/python', '.venv/Scripts/python.exe']) {
    const path = resolve(repoRoot, candidate);
    if (existsSync(path)) return path;
  }
  return 'python3';
}

/** Dumps the OpenAPI document as JSON using placeholder settings so no real secret or service is required. */
function readOpenApiSchema() {
  const code = 'import json; from apps.api.main import create_app; print(json.dumps(create_app().openapi(), sort_keys=True))';
  const output = execFileSync(pythonBinary(), ['-c', code], {
    cwd: repoRoot,
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    env: {
      ...process.env,
      ENVIRONMENT: process.env.ENVIRONMENT ?? 'test',
      REDIS_URL: process.env.REDIS_URL ?? 'redis://:placeholder@localhost:6379/0',
    },
  });
  // Skip any log line printed during import; the schema is the last line.
  const line = output.trim().split('\n').filter(Boolean).at(-1);
  return JSON.parse(line);
}

const schema = readOpenApiSchema();
const ast = await openapiTS(schema);
const banner = '/* eslint-disable */\n// Generated by scripts/generate-api-types.mjs from the FastAPI OpenAPI schema. Do not edit by hand.\n';
const generated = banner + astToString(ast);

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== generated) {
    console.error('api-types.gen.ts is stale. Run `npm run gen:api --workspace apps/web` and commit the result.');
    process.exit(1);
  }
  console.log('api-types.gen.ts is up to date.');
} else {
  writeFileSync(outFile, generated);
  console.log(`Wrote ${outFile}`);
}
