/** Lists media filters unavailable in the selected endpoint response, for rendering and request cleanup. */
export function inactiveMediaModeFilters(modeKey: string, selected: unknown): readonly (keyof BuiltinTypeOptions)[] {
  if (modeKey === 'omdb_mode' && selected === 'search') return OMDB_DETAIL_FILTERS;
  if (modeKey === 'tmdb_mode' && selected === 'changes') return TMDB_CHANGES_FILTERS;
  return [];
}

/**
 * Whether a per-type option applies under the current selections. An option bound to one mode is hidden and left out
 * of the request in every other mode, because the server rejects it there (422) rather than ignoring it.
 *
 * @param key Option spec key.
 * @param selected Current option values keyed by option name.
 * @returns False when the option belongs to a mode that is not selected; true otherwise.
 */
export function optionAppliesTo(key: string, selected: Record<string, unknown>): boolean {
  if (key === 'tvmaze_show_ids') return selected.tvmaze_mode === 'followed_shows';
  return true;
}

/** One per-type built-in option: how it renders and the bounds the server enforces. */
export type OptionSpec = {
  key: keyof BuiltinTypeOptions;
  kind: 'enum' | 'multi' | 'int' | 'float' | 'bool' | 'text' | 'tags';
  /** Enum / multi-enum values, identical to the server Literal (modules/connectors/provider_options.py). */
  values?: readonly string[];
  /** Multi-select cap, or the most comma-separated terms a `tags` field accepts. */
  max?: number;
  min?: number;
  /** Numeric ceiling (inclusive). */
  hi?: number;
  step?: number;
  maxLen?: number;
  /** Changes the upstream request, so a change restarts collection from the recent window. */
  native?: boolean;
  /** Text is forced to upper case (ISO codes). */
  upper?: boolean;
  /** Enum and checkbox values have translated labels under `optv.<value>` (otherwise the raw code is shown). */
  labelled?: boolean;
  /** Numeric identifiers are serialized as numbers after comma-list parsing. */
  numeric?: boolean;
  /** Retains explicit false and offers an unset provider-default choice. */
  nullable?: boolean;
  /** Native input format constraint; the server performs authoritative validation. */
  pattern?: string;
};

